/**
 * Ensures all 28 students of Kelas 1A are present in the list
 */
export const ensureKelas1AComplete = (currentStudents: Student[]): Student[] => {
  const existing1A = currentStudents.filter(s => {
    const k = (s.kelas || '').replace(/kelas\s*/i, '').replace(/[-\s]/g, '').trim().toUpperCase();
    return k === '1A';
  });

  // If already has 28 or more students, return current
  if (existing1A.length >= 28) {
    return currentStudents;
  }

  // Merge: Keep all non-1A students, and ensure all 28 students from KELAS_1A_STUDENTS are present
  const existingMap = new Map<string, Student>();
  currentStudents.forEach(s => existingMap.set(s.nisn, s));

  KELAS_1A_STUDENTS.forEach(kStudent => {
    if (!existingMap.has(kStudent.nisn)) {
      existingMap.set(kStudent.nisn, kStudent);
    } else {
      // Ensure kelas is strictly '1A' and waliKelas is filled
      const existing = existingMap.get(kStudent.nisn)!;
      existingMap.set(kStudent.nisn, {
        ...kStudent,
        ...existing,
        kelas: '1A',
        rombel: '1A',
        waliKelas: existing.waliKelas || 'Siti Rahmawati, S.Pd.',
        nipWaliKelas: existing.nipWaliKelas || '19840512 200902 2 006'
      });
    }
  });

  return Array.from(existingMap.values());
};

/**
 * Ensures attendance for Kelas 1A exists in the attendance list
 */
export const ensureKelas1AAttendance = (currentAttendance: AttendanceRecord[]): AttendanceRecord[] => {
  const has1AAttendance = currentAttendance.some(a => {
    const k = (a.kelas || '').replace(/kelas\s*/i, '').replace(/[-\s]/g, '').trim().toUpperCase();
    return k === '1A' && a.tanggal === '2026-09-18';
  });

  if (has1AAttendance) {
    return currentAttendance;
  }

  const generated1A = generateKelas1AAttendance();
  const existingKeys = new Set(currentAttendance.map(a => `${a.tanggal}_${a.nisn}`));
  const toAdd = generated1A.filter(a => !existingKeys.has(`${a.tanggal}_${a.nisn}`));

  return [...toAdd, ...currentAttendance];
};
